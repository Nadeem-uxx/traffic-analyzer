"""
Generates the sample traffic data used by the app.

Creates two files from the same random data:
  data/sample-traffic.csv  - the CSV you can also upload in the app
  data/sample-data.js      - the same CSV as a JS string, so index.html works
                             when opened directly (browsers block fetch() on file://)

Run:  python3 tools/generate_sample.py
"""
import math
import random

random.seed(42)  # same output every time

# junction name -> (traffic scale, rush-hour style)
# "office" = morning + evening peaks, "market" = midday/evening, "highway" = steady high flow
JUNCTIONS = {
    "Central Square":   (1.00, "office"),
    "Railway Station":  (0.90, "office"),
    "City Mall Chowk":  (0.75, "market"),
    "University Gate":  (0.60, "office"),
    "Highway Bypass":   (1.10, "highway"),
    "Old Market":       (0.50, "market"),
}


def gauss(x, mean, width):
    return math.exp(-((x - mean) ** 2) / (2 * width ** 2))


def hour_factor(hour, style):
    """Returns a 0..1 'how busy is this hour' value."""
    night = 0.06
    if style == "office":
        f = night + 0.95 * gauss(hour, 9, 1.6) + 0.85 * gauss(hour, 18, 1.8) + 0.35 * gauss(hour, 13, 2.5)
    elif style == "market":
        f = night + 0.45 * gauss(hour, 11, 2.0) + 0.95 * gauss(hour, 19, 2.2) + 0.30 * gauss(hour, 15, 2.0)
    else:  # highway
        f = 0.12 + 0.60 * gauss(hour, 14, 6.0) + 0.45 * gauss(hour, 8, 1.8) + 0.45 * gauss(hour, 18, 1.8)
    return min(f, 1.0)


rows = ["junction,hour,cars,bikes,buses,trucks"]
for name, (scale, style) in JUNCTIONS.items():
    for hour in range(24):
        busy = hour_factor(hour, style) * scale
        noise = lambda: random.uniform(0.9, 1.1)
        cars = int(700 * busy * noise())
        bikes = int(650 * busy * noise())
        buses = int(60 * busy * noise())
        # trucks are more common at night and on the highway
        truck_bias = 1.6 if style == "highway" else 1.0
        trucks = int((90 * busy + (25 if 22 <= hour or hour <= 5 else 0)) * truck_bias * noise())
        rows.append(f"{name},{hour},{cars},{bikes},{buses},{trucks}")

csv_text = "\n".join(rows) + "\n"

with open("data/sample-traffic.csv", "w") as f:
    f.write(csv_text)

with open("data/sample-data.js", "w") as f:
    f.write("// Auto-generated by tools/generate_sample.py - same data as sample-traffic.csv\n")
    f.write("const SAMPLE_CSV = `" + csv_text + "`;\n")

print("Wrote", len(rows) - 1, "rows")
